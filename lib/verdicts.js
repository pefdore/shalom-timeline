export function wrongVerdict(guess, member) {
  let hash = 0
  const key = normalize(guess) + monthKey()
  for (let i = 0; i < key.length; i++) hash = (hash * 31 + key.charCodeAt(i)) % 100000
  const v = WRONG_VERDICTS[hash % WRONG_VERDICTS.length]
  return { emoji: v.emoji, msg: v.msg.replace(/{name}/g, member || 'ce cher enquêteur') }
}
